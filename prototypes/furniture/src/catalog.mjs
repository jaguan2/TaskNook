export const FURNITURE = Object.fromEntries(Object.entries({ ...ready, ...ADDITIONAL_DESIGNS }).map(([key, design]) => {
  const item = ISO_ITEMS[key], group = ISO_ITEM_GROUPS.find(group => group.keys.includes(key));
  return [key, { label: item.label, width: item.foot[0], depth: item.foot[1], height: design.height / PIXELS_PER_UNIT,
    controlHeight: item.hitH, ...(item.forward && { forward: item.forward }), ...(item.seat != null && { seat: item.seat / PIXELS_PER_UNIT }),
    ...(item.layer != null && { layer: item.layer }), ...(item.softSeat && { softSeat: true }),
    ...(item.tintable === false && { tintable: false }),
    ...(item.stacks && { stacks: true }), ...(item.flicker && { flicker: true }), ...(item.glow && { glow: item.glow }),
    ...Object.fromEntries(['wall', 'persona', 'self', 'unique', 'roamer', 'backView', 'lie', 'toggleable'].filter(field => item[field] != null).map(field => [field, item[field]])),
    ...(item.surface != null && { surface: item.surface / PIXELS_PER_UNIT }),
    section: sectionId(group.label), colorRole: design.colorRole || 'upholstery', defaultColor: design.defaultColor || '#8baba0',
    description: descriptions[key] || design.description, ...(design.contact && { contact: design.contact }) }];
}));

export function migrationSections() {
  return ISO_ITEM_GROUPS.map((group, index) => {
    const exported = group.keys.filter(key => FURNITURE[key]);
    return { id: sectionId(group.label), order: index + 1, label: group.label, keys: group.keys,
      exported, pending: group.keys.filter(key => !FURNITURE[key]), total: group.keys.length,
      complete: exported.length === group.keys.length };
  });
}
